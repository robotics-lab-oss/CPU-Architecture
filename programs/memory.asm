; Memory Instruction Test
;
; Instructions tested:
;   LOAD
;   STORE
;   OUT
;   HALT
;
; Memory model:
;   8-bit address
;   Address range: 0x00 - 0xFF
; ============================================================


; ------------------------------------------------------------
; Step 1: Load value from memory
;
; A = MEM[0xF0]
; ------------------------------------------------------------

LOAD 0xF0


; ------------------------------------------------------------
; Step 2: Store accumulator into another address
;
; MEM[0xF1] = A
; ------------------------------------------------------------

STORE 0xF1


; ------------------------------------------------------------
; Step 3: Load the stored value again
;
; A = MEM[0xF1]
; ------------------------------------------------------------

LOAD 0xF1


; ------------------------------------------------------------
; Step 4: Output loaded value
; ------------------------------------------------------------

OUT


; ------------------------------------------------------------
; Step 5: Stop CPU
; ------------------------------------------------------------

HALT
