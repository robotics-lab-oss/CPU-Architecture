; ============================================================
; shell.asm
;
; MiniOS Shell
; MiniCPU 8-bit Architecture
;
; Responsibilities:
;   - Start shell
;   - Display prompt
;   - Read user input
;   - Process command
;   - Execute command
;   - Return to shell loop
;
; ============================================================


; ============================================================
; SHELL START
; ============================================================

SHELL_START:

    ; --------------------------------------------------------
    ; Initialize shell.
    ; --------------------------------------------------------

    NOP


; ============================================================
; SHELL MAIN LOOP
; ============================================================

SHELL_LOOP:

    ; --------------------------------------------------------
    ; Display shell prompt.
    ;
    ; Prompt output will be connected to the
    ; console implementation.
    ; --------------------------------------------------------

    JMP SHELL_PROMPT


; ============================================================
; SHELL PROMPT
; ============================================================

SHELL_PROMPT:

    ; --------------------------------------------------------
    ; Placeholder for prompt output.
    ;
    ; Future:
    ;   Print ">"
    ; --------------------------------------------------------

    NOP

    JMP SHELL_READ


; ============================================================
; READ COMMAND
; ============================================================

SHELL_READ:

    ; --------------------------------------------------------
    ; Read one character from console.
    ;
    ; IN:
    ;   A = input character
    ; --------------------------------------------------------

    IN

    ; Save input character.
    STORE 0xF5


    ; --------------------------------------------------------
    ; Process input.
    ; --------------------------------------------------------

    JMP SHELL_PROCESS


; ============================================================
; PROCESS COMMAND
; ============================================================

SHELL_PROCESS:

    ; --------------------------------------------------------
    ; Load input character.
    ; --------------------------------------------------------

    LOAD 0xF5


    ; --------------------------------------------------------
    ; Output received character.
    ;
    ; Basic echo functionality.
    ; --------------------------------------------------------

    OUT


    ; --------------------------------------------------------
    ; Continue shell loop.
    ; --------------------------------------------------------

    JMP SHELL_LOOP


; ============================================================
; UNKNOWN COMMAND
; ============================================================

SHELL_UNKNOWN:

    ; --------------------------------------------------------
    ; Unknown command handler.
    ; --------------------------------------------------------

    NOP

    JMP SHELL_LOOP


; ============================================================
; SHELL EXIT
; ============================================================

SHELL_EXIT:

    ; --------------------------------------------------------
    ; Exit shell and return to kernel.
    ; --------------------------------------------------------

    JMP KERNEL_RETURN
